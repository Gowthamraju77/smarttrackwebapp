const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), os = require("node:os");
const { chromium } = require(process.env.SMARTTRACK_PLAYWRIGHT_PATH || path.join(os.tmpdir(), "smarttrack-browser-tools", "node_modules", "playwright"));
const origin = new URL(process.env.BASE_URL || "http://127.0.0.1:3104").origin;
const output = process.env.SMARTTRACK_SCREENSHOTS || fs.mkdtempSync(path.join(os.tmpdir(), "smarttrack-notifications-ui-"));
const viewer = "synthetic_notification_viewer_" + "x".repeat(32);
const storage = "smarttrack.contact.browser.v1", checks = [];
(async () => {
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const posts = [], errors = []; let failSync = false;
    await context.route("**/api/live", r => r.fulfill({ status: 401, json: { error: "Synthetic feed locked" } }));
    await context.route("https://tiles.openfreemap.org/**", r => r.fulfill({ json: { version: 8, sources: {}, layers: [{ id: "background", type: "background", paint: { "background-color": "#e4eadc" } }] } }));
    await context.route("**/api/notifications/contact", async r => {
      const body = r.request().postDataJSON(); posts.push(body);
      assert.equal(r.request().headers().authorization, `Bearer ${viewer}`);
      if (failSync) return r.fulfill({ status: 503, json: { error: "Synthetic interruption. Your last synced schedule may still be active." } });
      const setting = body.preferences[body.mode];
      await r.fulfill({ json: { status: { available: true, email: true, sms: true, mode: body.mode, nextDue: setting.enabled ? new Date(Date.now()+setting.minutes*60000).toISOString() : null, deliveries: [] }, contacts: [{ id: "other-contact", name: "Synthetic Teammate", source: "relay", connected: true, last_seen_at: new Date().toISOString() }] } });
    });
    await context.route("**/api/journey/places?*", r => { const start = new URL(r.request().url()).searchParams.get("q").includes("Start"); return r.fulfill({ json: { places: [{ id: start ? "start" : "end", label: start ? "Synthetic Start" : "Synthetic Destination", latitude: 0, longitude: start ? 0 : 0.01 }] } }); });
    await context.route("**/api/journey/routes", r => r.fulfill({ json: { routes: [{ coordinates: [[0,0],[0.01,0]], distanceM: 1112, durationS: 120, provider: "Synthetic route" }] } }));
    const page = await context.newPage(); page.setDefaultTimeout(15000); page.on("pageerror", e => errors.push(e.message));
    await page.goto(origin + "/settings");
    await page.getByRole("heading", { name: "Hello, who’s joining?" }).waitFor();
    assert.equal(await page.locator(".app-shell").count(), 0);
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    await page.screenshot({ path: path.join(output,"contact-desktop.png"), fullPage:true });
    await page.setViewportSize({ width:390,height:844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({ path:path.join(output,"contact-mobile.png"),fullPage:true });
    await page.setViewportSize({ width:1440,height:1000 });
    await page.getByLabel("Your name",{exact:true}).fill("Synthetic Visitor");
    await page.getByLabel("Phone number",{exact:true}).fill("2025550123");
    await page.getByLabel("Email address",{exact:true}).fill("visitor@example.com");
    await page.getByRole("button",{name:"Enter workspace"}).click();
    await page.getByRole("alert").getByText(/Include your country code/).waitFor();
    await page.getByLabel("Phone number",{exact:true}).fill("+1 (202) 555-0123");
    await page.getByRole("button",{name:"Enter workspace"}).click();
    await page.getByRole("heading",{name:"Make it your workspace"}).waitFor();
    const settings = page.getByRole("region",{name:"Your notification rhythm"});
    await settings.getByText("Delivery not active",{exact:true}).waitFor();
    await settings.getByText(/A private device link/).waitFor();
    assert.equal(posts.length,0);
    checks.push("Empty-browser gate, contact validation, no verification, and responsive entry");
    const groups = settings.getByRole("group",{name:"Send every"});
    for(const [label,minutes] of [["20 min",20],["30 min",30],["1 hr",60],["3 hr",180],["5 hr",300],["10 hr",600],["24 hr",1440]]) {
      await groups.nth(0).getByRole("radio",{name:label,exact:true}).check();
      assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).preferences.general.minutes,storage),minutes);
    }
    await groups.nth(1).getByRole("radio",{name:"3 hr",exact:true}).check();
    await settings.getByRole("checkbox",{name:"Enable general email and SMS updates"}).check();
    await settings.getByRole("checkbox",{name:"Enable journey email and SMS updates"}).check();
    await page.reload(); await page.getByRole("heading",{name:"Make it your workspace"}).waitFor();
    assert.ok(await groups.nth(0).getByRole("radio",{name:"24 hr",exact:true}).isChecked());
    assert.ok(await groups.nth(1).getByRole("radio",{name:"3 hr",exact:true}).isChecked());
    await settings.getByRole("button",{name:"Edit contact details"}).click();
    await page.getByLabel("Your name",{exact:true}).fill("Synthetic Renamed");
    await page.getByRole("button",{name:"Save details",exact:true}).click();
    assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).profile.name,storage),"Synthetic Renamed");
    await page.evaluate(value=>sessionStorage.setItem("smarttrack.feed.viewer.v1",value),viewer);
    await settings.getByRole("button",{name:"Retry sync"}).click();
    await settings.getByText("Email + SMS configured",{exact:true}).waitFor();
    assert.equal(posts.at(-1).preferences.general.minutes,1440);
    assert.equal(posts.at(-1).preferences.journey.minutes,180);
    assert.equal(posts.at(-1).profile.phone,"+12025550123");
    checks.push("All intervals, both toggles, contact editing, reload persistence and authenticated sync");
    failSync=true; await settings.getByRole("button",{name:"Retry sync"}).click();
    await settings.getByText("Delivery not active",{exact:true}).waitFor();
    assert.match(await settings.innerText(),/last synced schedule may still be active/);
    failSync=false; await settings.getByRole("button",{name:"Retry sync"}).click();
    await settings.getByText("Email + SMS configured",{exact:true}).waitFor();
    await page.screenshot({path:path.join(output,"notifications-desktop.png"),fullPage:true});
    for(const width of [320,390,768]) { await page.setViewportSize({width,height:900}); assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Overflow at ${width}`); }
    await page.setViewportSize({width:390,height:844}); await page.screenshot({path:path.join(output,"notifications-mobile.png"),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(origin+"/devices");
    await page.getByRole("region",{name:"Device connections"}).getByText("Synthetic Teammate",{exact:true}).waitFor();
    await page.goto(origin+"/journeys");
    const planner=page.getByRole("region",{name:"Journey planner",exact:true});
    await planner.getByRole("searchbox",{name:"Search start place",exact:true}).fill("Start test");
    await planner.getByRole("button",{name:"Synthetic Start",exact:true}).click();
    await planner.getByRole("searchbox",{name:"Search destination place",exact:true}).fill("Destination test");
    await planner.getByRole("button",{name:"Synthetic Destination",exact:true}).click();
    await planner.getByRole("radio",{name:"Choose route 1",exact:true}).check();
    const journeySync = page.waitForResponse(r => r.url().endsWith("/api/notifications/contact") && r.request().postDataJSON().mode === "journey");
    await planner.getByRole("button",{name:"Start journey",exact:true}).click();
    await journeySync;
    await page.waitForURL(u=>u.pathname==="/navigation");
    await page.waitForFunction(()=>localStorage.getItem("smarttrack.notifications.mode.v1")==="journey");
    const journeySettings=page.getByRole("region",{name:"Journey updates",exact:true});
    await journeySettings.getByText("Email + SMS configured",{exact:true}).waitFor();
    assert.equal(posts.at(-1).mode,"journey");
    const second=await context.newPage(); await second.goto(origin+"/settings");
    await second.getByRole("heading",{name:"Make it your workspace"}).waitFor();
    assert.equal(await second.evaluate(()=>localStorage.getItem("smarttrack.notifications.mode.v1")),"journey","Idle tab must preserve active journey schedule");
    await second.close();
    const generalSync = page.waitForResponse(r => r.url().endsWith("/api/notifications/contact") && r.request().postDataJSON().mode === "general");
    await page.getByRole("button",{name:"Cancel waiting",exact:true}).click();
    await generalSync;
    await page.waitForFunction(()=>localStorage.getItem("smarttrack.notifications.mode.v1")==="general");
    await journeySettings.getByText("Email + SMS configured",{exact:true}).waitFor();
    assert.equal(posts.at(-1).mode,"general");
    checks.push("Journey start and cancellation switch schedules; a new tab retains the active mode and contact");
    await page.emulateMedia({reducedMotion:"reduce"});
    assert.equal(await journeySettings.evaluate(e=>getComputedStyle(e).animationName),"none");
    assert.deepEqual(errors,[]);
    checks.push("Shared connection names, honest sync failures, responsive settings and reduced motion; no runtime errors");
    console.log(JSON.stringify({status:"passed",checks,screenshots:output},null,2)); await context.close();
  } finally {await browser.close();}
})().catch(error=>{console.error(JSON.stringify({status:"failed",checks,error:error.stack,screenshots:output},null,2));process.exitCode=1;});
